#!/usr/bin/env bash
# Builds gcx-commands.txt for gcx-guard.sh: one line per gcx leaf command, tagged
# R (read, Claude may run it) or W (write or unclear, blocked).
# Run it again after each gcx upgrade.
set -euo pipefail

DIR="$(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")" && pwd)"
OUT="$DIR/gcx-commands.txt"

is_read() {
  local path="$1" verb="${1##* }"
  case "$path" in
    assistant | assistant\ *) return 1 ;;
    api | docs | docs\ *) return 0 ;;
  esac
  case "$verb" in
    list | list-* | get | get-* | query | query-* | search | search-* | status | labels | \
      label-names | label-values | metric-names | series | describe-table | timeline | schema | \
      stats | metadata | health | inspect | view | diff | current-context | path | check | help | \
      help-tree | commands | version | snapshot | pull | export) return 0 ;;
  esac
  return 1
}

paths=$(gcx commands -o json --include-hidden --no-color 2>/dev/null |
  jq -rs '.[] | select(type == "object" and has("commands")) | .commands
    | .. | objects | select(has("full_path") and ((.subcommands // []) | length == 0))
    | .full_path | sub("^gcx "; "")' | sort -u)

[ -n "$paths" ] || {
  echo "gcx commands returned no commands" >&2
  exit 1
}

{
  echo "# Generated by gcx-commands-gen.sh from $(gcx --version 2>/dev/null | head -1). Do not edit by hand."
  echo "# R = read (allowed for Claude), W = write or unclear (blocked)."
  while IFS= read -r p; do
    if is_read "$p"; then echo "R $p"; else echo "W $p"; fi
  done <<<"$paths"
} >"$OUT"

echo "Wrote $OUT: $(grep -c '^R ' "$OUT") read, $(grep -c '^W ' "$OUT") write."
